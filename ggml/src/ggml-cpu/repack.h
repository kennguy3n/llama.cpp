template <int K> constexpr int QK_0() {
    if constexpr (K == 4) {
        return QK4_0;
    }
    if constexpr (K == 8) {
        return QK8_0;
    }
    return -1;
}

template <int K, int N> struct block {
    ggml_half d[N];                         // deltas for N qK_0 blocks
    int8_t    qs[(QK_0<K>() * N * K) / 8];  // quants for N qK_0 blocks
};

// control size
static_assert(sizeof(block<4, 4>) == 4 * sizeof(ggml_half) + QK8_0 * 2, "wrong block<4,4> size/padding");
static_assert(sizeof(block<4, 8>) == 8 * sizeof(ggml_half) + QK8_0 * 4, "wrong block<4,8> size/padding");
static_assert(sizeof(block<8, 4>) == 4 * sizeof(ggml_half) + QK8_0 * 4, "wrong block<8,4> size/padding");
static_assert(sizeof(block<8, 8>) == 8 * sizeof(ggml_half) + QK8_0 * 8, "wrong block<8,8> size/padding");

using block_q4_0x4 = block<4, 4>;
using block_q4_0x8 = block<4, 8>;
using block_q8_0x4 = block<8, 4>;
using block_q8_0x8 = block<8, 8>;

struct block_q4_Kx8 {
    ggml_half d[8];      // super-block scale for quantized scales
    ggml_half dmin[8];   // super-block scale for quantized mins
    uint8_t scales[96];  // scales and mins, quantized with 6 bits
    uint8_t qs[1024];    // 4--bit quants
};

static_assert(sizeof(block_q4_Kx8) == sizeof(ggml_half) * 16 + K_SCALE_SIZE * 8 + QK_K * 4, "wrong q4_K block size/padding");

struct block_q2_Kx8 {
    ggml_half d[8];      // super-block scale for quantized scales
    ggml_half dmin[8];   // super-block scale for quantized mins
    uint8_t scales[128];  // scales and mins, quantized with 4 bits
    uint8_t qs[512];    // 2--bit quants
};

static_assert(sizeof(block_q2_Kx8) == sizeof(ggml_half) * 16 + QK_K/2 + QK_K * 2, "wrong q2_K block size/padding");

struct block_q5_Kx8 {
    ggml_half d[8];              // super-block scale for quantized scales
    ggml_half dmin[8];           // super-block scale for quantized mins
    uint8_t   scales[96];        // scales and mins, quantized with 6 bits
    uint8_t   qh[QK_K * 8 / 8];  // high bits of 5-bit quants
    uint8_t   qs[QK_K * 8 / 2];  // low bits of 5-bit quants (in groups of 4)
};

static_assert(sizeof(block_q5_Kx8) == sizeof(ggml_half) * 16 + K_SCALE_SIZE * 8 + QK_K * 5,
              "wrong q5_K block size/padding");

struct block_q6_Kx8 {
    ggml_half d[8];
    int8_t    scales[QK_K / 16 * 8];
    uint8_t   ql[QK_K / 2 * 8];  // low bits of 6-bit quants (groups of 2)
    uint8_t   qh[QK_K / 4 * 8];  // high bits of 6-bit quants (groups of 4)
};

static_assert(sizeof(block_q6_Kx8) == sizeof(ggml_half) * 8 + QK_K / 16 * 8 + 3 * QK_K / 4 * 8,
              "wrong q6_K block size/padding");

struct block_q8_Kx4 {
    float d[4];              // delta
    int8_t qs[QK_K * 4];     // quants
    int16_t bsums[QK_K / 4]; // sum of quants in groups of 16
};

static_assert(sizeof(block_q8_Kx4) == sizeof(float) * 4 + QK_K * 4 + (QK_K / 4) * sizeof(int16_t), "wrong q8_K block size/padding");

struct block_iq4_nlx4 {
    ggml_half d[4];            // deltas for 4 iq4_nl blocks
    uint8_t   qs[QK4_NL * 2];  // nibbles / quants for 4 iq4_nl blocks
};

static_assert(sizeof(block_iq4_nlx4) == 4 * sizeof(ggml_half) + QK4_NL * 2, "wrong iq4_nlx4 block size/padding");

struct block_iq4_nlx8 {
    ggml_half d[8];            // deltas for 8 iq4_nl blocks
    uint8_t   qs[QK4_NL * 4];  // nibbles / quants for 8 iq4_nl blocks
};

static_assert(sizeof(block_iq4_nlx8) == 8 * sizeof(ggml_half) + QK4_NL * 4, "wrong iq4_nlx8 block size/padding");

struct block_mxfp4x4 {
    uint8_t e[4];
    uint8_t qs[QK_MXFP4 * 2];
};
static_assert(sizeof(block_mxfp4x4) == 4 + QK_MXFP4 * 2, "wrong mxfp4x4 block size/padding");

struct block_mxfp4x8 {
    uint8_t e[8];
    uint8_t qs[QK_MXFP4 * 4];
};
static_assert(sizeof(block_mxfp4x8) == 8 + QK_MXFP4 * 4, "wrong mxfp4x8 block size/padding");

// Phase 3 (PR #12): 4-row-interleaved repack of `Q1_0_g128` for the AVX2
// runtime-repack path. See `docs/avx2-repack-design/03-design-brief.md` and
// the Phase 2 microbench at `tools/microbench/q1_g128_repack.cpp` for the
// layout rationale and measured 1.28x speedup vs. the single-row AVX2
// kernel on Zen 3.
//
// On-disk byte layout per 128-weight × 4-row block (72 B total):
//
//   [d0 d1 d2 d3]                  // 8 B: 4 ggml_half deltas
//   [r0_sb0 r1_sb0 r2_sb0 r3_sb0]  // 16 B: 4-byte interleave per row, sub-block 0
//   [r0_sb1 r1_sb1 r2_sb1 r3_sb1]  // 16 B: sub-block 1
//   [r0_sb2 r1_sb2 r2_sb2 r3_sb2]  // 16 B: sub-block 2
//   [r0_sb3 r1_sb3 r2_sb3 r3_sb3]  // 16 B: sub-block 3
struct block_q1_0_g128x4 {
    ggml_half d[4];   // deltas for 4 rows
    uint8_t   qs[64]; // 4 sub-blocks × 4 rows × 4 bytes = 64 bytes
};
static_assert(sizeof(block_q1_0_g128x4) == 4 * sizeof(ggml_half) + QK1_0_g128 * 4 / 8,
              "wrong q1_0_g128x4 block size/padding");
static_assert(sizeof(block_q1_0_g128x4) == 4 * sizeof(block_q1_0_g128),
              "block_q1_0_g128x4 must be size-equivalent to 4 rows of block_q1_0_g128");

// 4-row-interleaved repack of `Q2_0` (2-bit ternary, 128-weight blocks) for
// the AVX2 runtime-repack path. Mirrors the `block_q1_0_g128x4` design above;
// see `docs/avx2-repack-design/09-q2-0-phase.md` for the layout rationale.
//
// On-disk GGUF is unchanged: this layout is produced in-memory at tensor-init
// time. Each block packs 128 weights × 4 rows (136 B total):
//
//   [d0 d1 d2 d3]                  // 8 B: 4 ggml_half deltas
//   [r0_sb0 r1_sb0 r2_sb0 r3_sb0]  // 32 B: 8-byte interleave per row, sub-block 0
//   [r0_sb1 r1_sb1 r2_sb1 r3_sb1]  // 32 B: sub-block 1
//   [r0_sb2 r1_sb2 r2_sb2 r3_sb2]  // 32 B: sub-block 2
//   [r0_sb3 r1_sb3 r2_sb3 r3_sb3]  // 32 B: sub-block 3
//
// Sub-block k holds 32 ternary codes per row (8 packed bytes per row, 2 bits
// per code, 4 codes per byte), aligned to the 4-row q8_0 sub-blocks consumed
// by the GEMV/GEMM kernels.
struct block_q2_0x4 {
    ggml_half d[4];    // deltas for 4 rows
    uint8_t   qs[128]; // 4 sub-blocks × 4 rows × 8 bytes = 128 bytes
};
static_assert(sizeof(block_q2_0x4) == 4 * sizeof(ggml_half) + QK2_0 * 4 / 4,
              "wrong q2_0x4 block size/padding");
static_assert(sizeof(block_q2_0x4) == 4 * sizeof(block_q2_0),
              "block_q2_0x4 must be size-equivalent to 4 rows of block_q2_0");


